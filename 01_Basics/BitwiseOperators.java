public class BitwiseOperators{

    public static void main(String args[]){
        
        int num1 = 21;
        int num2 = 26;

        System.out.println(num1&num2);
        System.out.println(num1|num2);
        System.out.println(num1^ num2);
        System.out.println(~num1);
        System.out.println(num1<<num2);
        System.out.println(num1>>num2);
        
    }
}
