public class AssignmentOperators{

    public static void main(String args[]){
        
        double num1 = 21;
        double num2 = 26.7;

        System.out.println(num1+=num2);
        System.out.println(num1-=num2);
        System.out.println(num1*= num2);
        System.out.println(num1/=num2);
        System.out.println(num1%=num2);
        
    }
}
