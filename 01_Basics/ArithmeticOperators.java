public class ArithmeticOperators{

    public static void main(String args[]){
        
        int num1 = 21;
        double num2 = 26.7;
        int num3 = 29;
        

        System.out.println(num1+num2);
        System.out.println(num2-num3);
        System.out.println(num3* num1);
        System.out.println(num1/num2);
        System.out.println(num1%num2);
        
    }
}
